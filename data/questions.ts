// ─── Helpers ──────────────────────────────────────────────────────────────────

export function getQuestionsByModule(moduleSlug: string): Question[] {
  return questions.filter((q) => q.moduleSlug === moduleSlug);
}

export function getQuestionsByLevel(level: ExamLevel): Question[] {
  return questions.filter((q) => q.level.includes(level));
}

export function getQuestionById(id: string): Question | undefined {
  return questions.find((q) => q.id === id);
}

export function getExamQuestions(level: ExamLevel, count = 40): Question[] {
  const pool = questions.filter((q) => q.level.includes(level));
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}

export function getFreeQuestions(count = 20): Question[] {
  const pool = questions.filter((q) => q.level.includes('CSP'));
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

export function getQuestionStats() {
  return {
    total: questions.length,
    csp: questions.filter((q) => q.level.includes('CSP')).length,
    cr: questions.filter((q) => q.level.includes('CR')).length,
    nat: questions.filter((q) => q.level.includes('NAT')).length,
    byModule: ['republique', 'droits', 'institutions', 'histoire', 'vie-en-france'].map((slug) => ({
      slug,
      count: questions.filter((q) => q.moduleSlug === slug).length,
    })),
  };
}
