/**
 * Fiches bonus — grandes figures françaises & grands lieux du programme.
 * Contenu complémentaire, accessible depuis /fiches.
 *
 * Palette : tricolore FR (bleu → blanc → rouge), cf. design system.
 */
export interface Fiche {
  slug: string;
  /**
   * Famille de la fiche. Chaque famille vise un type de requête distinct :
   *  figure/lieu  — entités culturelles et patrimoniales
   *  symbole      — emblèmes de la République (drapeau, hymne, devise…)
   *  institution  — organes et textes fondateurs
   *  evenement    — dates et faits historiques du programme civique
   */
  category: 'figure' | 'lieu' | 'symbole' | 'institution' | 'evenement';
  name: string;
  /** Rôle / dates affichés sous le nom, ex: "1867–1934 · Physicienne et chimiste" */
  subtitle: string;
  /** Court tag affiché sur la carte verticale, ex: "Sciences", "Monument" */
  tag: string;
  image: string;
  imageAlt: string;
  credit: string;
  color: string;
  colorEnd: string;
  paragraph: string;
  keyPoints: string[];
  /** Repères chiffrés affichés en grille (dates, œuvres, actions, classements...) */
  facts: { label: string; value: string }[];
  /**
   * Recadrage personnalisé de l'image — utile quand la photo source a un
   * cadrage (panorama, ciel dominant...) qui ne correspond pas bien aux
   * formats d'affichage par défaut.
   * - card*  : vignette portrait de /fiches (défaut object-position 'center 22%')
   * - hero*  : bandeau large de la page détail (défaut object-position 'center 25%')
   * Scale > 1 effectue un zoom (recadrage plus serré) sur la zone ciblée.
   */
  cardImagePosition?: string;
  cardImageScale?: number;
  heroImagePosition?: string;
  heroImageScale?: number;
}

